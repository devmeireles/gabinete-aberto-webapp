export const ONE_DAY_MS: number = 24 * ONE_HOUR_MS;
export const SEVEN_DAYS_MS: number = 7 * ONE_DAY_MS;
export const THIRTY_DAYS_MS: number = 30 * ONE_DAY_MS;
